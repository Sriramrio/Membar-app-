import fs from 'node:fs';
const checks=[];const add=(name,ok)=>checks.push([name,Boolean(ok)]);
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const env=fs.readFileSync('src/config/env.ts','utf8');
const budget=fs.readFileSync('src/config/performanceBudgets.ts','utf8');
const api=fs.readFileSync('src/services/api/apiClient.ts','utf8');
const cursor=fs.readFileSync('src/hooks/useDomainCursorPage.ts','utf8');
const debounce=fs.readFileSync('src/hooks/useDebouncedValue.ts','utf8');
const governed=fs.readFileSync('src/hooks/useGovernedCommand.ts','utf8');
const commandExec=fs.readFileSync('src/services/commands/commandExecutor.ts','utf8');
const perf=fs.readFileSync('src/services/performance/performanceMonitor.ts','utf8');
add('Package version is V7.1.0',pkg.version==='7.1.0');
add('Runtime fallback version is V7.1.0',env.includes("'7.1.0'"));
add('Performance budget defines UI/read/command/search targets',/uiFeedbackMs/.test(budget)&&/readP95Ms/.test(budget)&&/commandP95Ms/.test(budget)&&/searchP95Ms/.test(budget));
add('Performance budget bounds API page size',/maxPageSize:100/.test(budget));
add('API client emits latency telemetry',api.includes('api.request.completed')&&api.includes('durationMs'));
add('API client classifies latency against central budgets',api.includes('classifyLatency'));
add('V7.1 aggregate validation script is registered',Boolean(pkg.scripts['validate:v71:source']));
add('Cursor pages preserve stale data during background refresh',cursor.includes('refreshing')&&cursor.includes('stale')&&cursor.includes('lastUpdatedAt'));
add('Cursor pages capture request duration',cursor.includes('requestDurationMs'));
add('Reusable search debounce hook exists',debounce.includes('setTimeout')&&debounce.includes('delayMs'));
add('Governed commands measure duration against command budget',governed.includes('command.completed')&&governed.includes("classifyLatency(durationMs, 'command')"));
add('Governed command failures/throws are performance observable',governed.includes('command.failed')&&governed.includes('command.exception'));
add('Offline command errors retain operation correlation',commandExec.includes('correlationId:options.command.commandId'));
add('Performance monitor includes LCP/CLS/INP/long-task coverage',perf.includes('web-vital.lcp')&&perf.includes('web-vital.cls')&&perf.includes('web-vital.inp')&&perf.includes('main-thread.long-task'));
for(const [n,ok] of checks)console.log(`${ok?'PASS':'FAIL'}: ${n}`);const failed=checks.filter(x=>!x[1]);console.log(`SETHU V7.1 enterprise standard foundation: ${checks.length-failed.length}/${checks.length}`);if(failed.length)process.exit(1);
