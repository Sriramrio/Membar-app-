import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const checks=[];const check=(name,ok)=>{checks.push([name,Boolean(ok)]);if(!ok)process.exitCode=1};
const gateway=read('src/services/realtimeGateway.ts');
const command=read('src/services/commandGateway.ts');
const contracts=read('src/contracts/runtimeContracts.ts');
const cross=read('src/services/crossTab.ts');
const vite=read('vite.config.ts');
const env=read('.env.simulator');
check('contract version 3.5.0',contracts.includes("ORGANISATIONAL_CONTRACT_VERSION='3.5.0'"));
check('realtime event version supported',contracts.includes('version?:number'));
check('realtime duplicate event dedupe',gateway.includes('this.seen.has(e.id)'));
check('realtime stale aggregate version rejection',gateway.includes('e.version<latest'));
check('unknown outcome on command timeout',command.includes("code:'COMMAND_TIMEOUT'")&&command.includes('unknownOutcome:true'));
check('unknown outcome on command transport loss',command.includes("COMMAND_NETWORK_OUTCOME_UNKNOWN")&&command.includes('VERIFY_BEFORE_RETRY'));
check('same-tab and sibling-tab runtime event delivery',cross.includes('for(const listener of listeners)listener(event)')&&cross.includes('channel?.postMessage(event)'));
check('simulator uses same-origin api proxy',vite.includes("'/api'")&&vite.includes('SETHU_SIMULATOR_TARGET'));
check('simulator mode keeps mocks disabled',env.includes('VITE_USE_MOCKS=false'));
for(const [n,ok] of checks)console.log(`${ok?'PASS':'FAIL'} ${n}`);
console.log(`Runtime resilience: ${checks.filter(x=>x[1]).length}/${checks.length}`);
