import type {OrgLevel} from '@/domain/types';
export interface RouteAccessPolicy{requiredPermission:string;capability:string;minimumLevel?:OrgLevel;navigationGroup:string;mobilePriority:'PRIMARY'|'SECONDARY'|'CONTEXTUAL'}
const read=(resource:string,capability:string,navigationGroup:string,minimumLevel?:OrgLevel,mobilePriority:RouteAccessPolicy['mobilePriority']='SECONDARY'):RouteAccessPolicy=>({requiredPermission:'org:read',capability:`${resource}:${capability}`,minimumLevel,navigationGroup,mobilePriority});
export function routeAccessPolicy(path:string):RouteAccessPolicy{
  if(path==='/org/today')return read('workspace','today','Workspace',undefined,'PRIMARY');
  if(path==='/org/action-centre')return read('task','action-centre','Workspace',undefined,'PRIMARY');
  if(path==='/org/converse')return read('converse','read','Workspace',undefined,'PRIMARY');
  if(path==='/org/calendar')return read('calendar','read','Workspace',undefined,'PRIMARY');
  if(path==='/org/more')return read('workspace','more','Workspace',undefined,'PRIMARY');
  if(path.startsWith('/org/approvals'))return read('approval','read','Workspace');
  if(path==='/org/search')return read('search','read','Workspace');
  if(path.startsWith('/org/tasks'))return read('task','read','Execution & Planning');
  if(path.startsWith('/org/actions'))return read('action','read','Execution & Planning');
  if(path.startsWith('/org/meetings')||path==='/org/mom')return read('meeting','read','Execution & Planning');
  if(path.startsWith('/org/chapters'))return read('chapter','read','Chapter Operations');
  if(path==='/org/mc')return read('chapter','read','Chapter Operations');
  if(path==='/org/visitors')return read('member','read','Chapter Operations');
  if(path.startsWith('/org/members'))return read('member','read','Chapter Operations');
  if(path.startsWith('/org/member-cases'))return read('member-case','read','Chapter Operations');
  if(path==='/org/growth')return read('member-growth','read','Chapter Operations');
  if(path==='/org/networking')return read('networking','read','Chapter Operations');
  if(path.startsWith('/org/committees'))return read('committee','read','Chapter Operations');
  if(path==='/org/attendance')return read('attendance','read','Chapter Operations');
  if(path==='/org/kyt')return read('kyt','read','Chapter Operations');
  if(path==='/org/member-presentations')return read('member-presentation','read','Chapter Operations');
  if(path.startsWith('/org/programmes')||path.startsWith('/org/projects'))return read('programme','read','Execution & Planning');
  if(path.startsWith('/org/events'))return read('event','read','Execution & Planning');
  if(path.startsWith('/org/plans')||path.startsWith('/org/goals'))return read('goal','read','Execution & Planning');
  if(path==='/org/chapter-coordinators')return read('chapter','read','Hierarchy','REGION');
  if(path.startsWith('/org/regions'))return read('region','read','Hierarchy','REGION');
  if(path.startsWith('/org/cities'))return read('city','read','Hierarchy','CITY');
  if(path.startsWith('/org/states'))return read('state','read','Hierarchy','STATE');
  if(path==='/org/national')return read('national','read','Hierarchy','NATIONAL');
  if(path==='/org/management')return read('management','read','Hierarchy','MANAGEMENT');
  if(path.startsWith('/org/support'))return read('support-request','read','Control & Support');
  if(path.startsWith('/org/escalations'))return read('escalation','read','Control & Support');
  if(path.startsWith('/org/exceptions'))return read('exception','read','Control & Support');
  if(path.startsWith('/org/risks'))return read('risk','read','Control & Support');
  if(path.startsWith('/org/issues'))return read('issue','read','Control & Support');
  if(path.startsWith('/org/decisions'))return read('decision','read','Control & Support');
  if(path.startsWith('/org/communications'))return read('communication','read','Communication & Knowledge');
  if(path.startsWith('/org/polls'))return read('poll','read','Communication & Knowledge');
  if(path.startsWith('/org/surveys'))return read('survey','read','Communication & Knowledge');
  if(path.startsWith('/org/documents')||path==='/org/resources')return read('document','read','Communication & Knowledge');
  if(path.startsWith('/org/notifications'))return read('notification','read','Communication & Knowledge');
  if(path.startsWith('/org/alerts'))return read('alert','read','Communication & Knowledge');
  if(path==='/org/roles-access')return read('effective-access','read','Assurance');
  if(path==='/org/availability'||path==='/org/delegations'||path==='/org/handover')return read('continuity','read','Assurance');
  if(path.startsWith('/org/handoffs'))return read('handoff','read','Assurance');
  if(path.startsWith('/org/data-quality'))return read('data-quality','read','Assurance');
  if(path==='/org/audit'||path==='/org/timeline')return read('audit','read','Assurance');
  if(path==='/org/reports'||path==='/org/analytics')return read('report','read','Assurance');
  if(path.startsWith('/org/jobs')||path==='/org/imports'||path==='/org/exports')return read('job','read','Assurance');
  if(path==='/org/people')return read('people','read','Chapter Operations');
  if(path==='/org/membership-dues'||path==='/org/payment-exceptions')return read('dues','read','Chapter Operations');
  if(path.startsWith('/org/trust-payments')||path.startsWith('/org/trust/payments'))return read('trust-payments','verify','Chapter Operations');
  if(path.startsWith('/org/trustee/leadership')||path.startsWith('/org/chapter-leadership'))return read('chapter-leadership','manage','Chapter Operations');
  return read('workspace','read','Other');
}
